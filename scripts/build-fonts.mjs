// Regenerates client/src/theme/fonts. Only needed when the set of display characters changes.
// Run from the project folder: node scripts/build-fonts.mjs
import { copyFile, mkdir, readdir, readFile, writeFile } from 'node:fs/promises';
import { join } from 'node:path';
import subsetFont from 'subset-font';

const OUT = 'client/src/theme/fonts';

// The only Japanese characters the interface draws, so a whole Japanese font is never downloaded.
const MINCHO_GLYPHS = '済優勝';
const PIXEL_GLYPHS = '壱弐参肆';

// Used as published. DSEG has a Reserved Font Name, which rules out modifying it, so it isn't subset.
const COPIES = [
  ['node_modules/@fontsource/zen-kaku-gothic-new/files/zen-kaku-gothic-new-latin-400-normal.woff2', 'gothic-400.woff2'],
  ['node_modules/@fontsource/zen-kaku-gothic-new/files/zen-kaku-gothic-new-latin-500-normal.woff2', 'gothic-500.woff2'],
  ['node_modules/@fontsource/zen-old-mincho/files/zen-old-mincho-latin-500-normal.woff2', 'mincho-500.woff2'],
  // Macrons for romanized Japanese words like "ō". Only downloaded when one appears.
  ['node_modules/@fontsource/zen-old-mincho/files/zen-old-mincho-latin-ext-500-normal.woff2', 'mincho-ext-500.woff2'],
  ['node_modules/dseg/fonts/DSEG7-Classic/DSEG7Classic-Bold.woff2', 'dseg7-bold.woff2'],
];

/** Fontsource splits Japanese fonts into numbered slices. Find the ones holding these characters. */
async function slicesContaining(pkg, prefix, glyphs, weight) {
  const css = await readFile(`node_modules/@fontsource/${pkg}/${weight}.css`, 'utf8');
  const wanted = new Set(Array.from(glyphs, (glyph) => glyph.codePointAt(0)));
  const slices = new Set();
  for (const match of css.matchAll(/files\/([^)]+?\.woff2)\).*?unicode-range:\s*([^;]+);/gs)) {
    const [, file, ranges] = match;
    for (const range of ranges.split(',')) {
      const [start, end] = range.trim().replace('U+', '').split('-').map((text) => parseInt(text, 16));
      for (const point of wanted) {
        if (point >= start && point <= (end ?? start)) slices.add(file);
      }
    }
  }
  if (slices.size === 0) throw new Error(`No ${prefix} slice holds ${glyphs}`);
  return [...slices];
}

/** One tiny file per character, so a phone downloads only the ones on its screen. */
async function subset(pkg, glyphs, weight, outName) {
  for (const glyph of glyphs) {
    const [file] = await slicesContaining(pkg, outName, glyph, weight);
    const code = glyph.codePointAt(0).toString(16);
    await writeSubset(pkg, file, glyph, `${outName}-${code}.woff2`);
  }
}

async function writeSubset(pkg, file, glyphs, outName) {
  const source = await readFile(`node_modules/@fontsource/${pkg}/files/${file}`);
  const output = await subsetFont(source, glyphs, { targetFormat: 'woff2' });
  await writeFile(join(OUT, outName), output);
}

await mkdir(OUT, { recursive: true });
for (const [source, name] of COPIES) await copyFile(source, join(OUT, name));
await subset('zen-old-mincho', MINCHO_GLYPHS, '500', 'mincho');
await subset('dotgothic16', PIXEL_GLYPHS, '400', 'pixel');

await writeFile(
  join(OUT, 'LICENSES.md'),
  `# Font licenses

All fonts here are under the SIL Open Font License 1.1.

- Zen Kaku Gothic New: The Zen Kaku Gothic New Project Authors (Latin subset)
- Zen Old Mincho: The Zen Old Mincho Project Authors (Latin subset, plus a few display characters)
- DotGothic16: The DotGothic16 Project Authors (a few display characters only)
- DSEG7 Classic: keshikan, with Reserved Font Name "DSEG" (unmodified)

Generated by scripts/build-fonts.mjs.
`,
);

for (const file of await readdir(OUT)) {
  const { size } = await import('node:fs').then(({ statSync }) => statSync(join(OUT, file)));
  console.log(file, `${(size / 1024).toFixed(1)} KB`);
}
